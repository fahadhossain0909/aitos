#!/usr/bin/env python3
"""Generate src/tokens.css: one --c-<hex> design token per colour literal.

The Olive palette (the original console look) is the source of truth. The
Terminal (neutral dark, blue accent) and Ivory (light) palettes are derived
from it deterministically, so a new colour only needs to be added once.
Run from desktop/:  python3 scripts/generate-theme-tokens.py
"""
import colorsys, pathlib, re

SRC = pathlib.Path(__file__).resolve().parent.parent / "src"
HEX = re.compile(r"#(?:[0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{4}|[0-9a-fA-F]{3})(?![0-9a-zA-Z_-])")
TOKEN = re.compile(r"var\(--c-([0-9a-f]{6}(?:[0-9a-f]{2})?)\)")


def norm(h: str) -> str:
    h = h.lstrip("#").lower()
    return "".join(c * 2 for c in h) if len(h) in (3, 4) else h


def parse(h: str):
    r, g, b = (int(h[i : i + 2], 16) / 255 for i in (0, 2, 4))
    return (*colorsys.rgb_to_hls(r, g, b), h[6:])  # H, L, S, alpha-suffix


def fmt(H, L, S, alpha) -> str:
    r, g, b = colorsys.hls_to_rgb(H % 1, max(0, min(1, L)), max(0, min(1, S)))
    return "".join(f"{round(v * 255):02x}" for v in (r, g, b)) + alpha


def terminal(h: str) -> str:
    H, L, S, a = parse(h)
    deg = H * 360
    if S < 0.45:  # olive-tinted neutrals -> cool neutral greys
        H, S = 218 / 360, min(S * 0.25, 0.12)
    elif 70 <= deg <= 125:  # lime accent -> single blue accent
        H, S = 214 / 360, min(S, 0.9)
    return fmt(H, L, S, a)


def ivory(h: str) -> str:
    H, L, S, a = parse(h)
    L2 = min(1 - L, 0.42) if 0.38 < L < 0.72 else 1 - L
    if L2 > 0.82 and S < 0.35:  # warm paper surfaces
        H, S = 48 / 360, min(S, 0.25)
    return fmt(H, L2, min(S, 0.6), a)


def main() -> None:
    sources = [p for p in SRC.rglob('*') if p.suffix in {".css", ".tsx"} and p.name not in {"tokens.css", "themes.css"}]
    used: set[str] = set()
    for p in sources:
        text = p.read_text()
        used |= {norm(m) for m in HEX.findall(text)} | set(TOKEN.findall(text))
    used = sorted(used)
    blocks = [
        ("/* Olive dark: the original palette (default). */\n:root", lambda h: h),
        ('/* Terminal: neutral dark, single blue accent. */\nhtml[data-theme="terminal"]', terminal),
        ('/* Ivory: light daylight palette. */\nhtml[data-theme="ivory"]', ivory),
    ]
    out = ["/* GENERATED by scripts/generate-theme-tokens.py - do not edit by hand. */\n"]
    for selector, fn in blocks:
        out.append(selector + " {")
        out += [f"  --c-{h}: #{fn(h)};" for h in used]
        out.append("}\n")
    (SRC / "tokens.css").write_text("\n".join(out))
    print(f"{len(used)} tokens x {len(blocks)} themes")


if __name__ == "__main__":
    main()
